#[derive(Default)]
pub struct ApplyChatTemplateArgs<'a, I, R = Role, T = String>
where
    I: IntoIterator<Item = Chat<'a, R, T>>,
    R: Serialize + 'a,
    T: Serialize + ToString + 'a,
{
    // pub conversations: &'a [Conversation<R, T>],
    pub conversations: I,
    /// Tool schemas (a JSON array of `{type, function:{name, description,
    /// parameters}}`) exposed to the template as the `tools` variable. `None`
    /// renders a tool-less prompt.
    pub tools: Option<serde_json::Value>,
    pub documents: Option<&'a [Document]>,
    pub model_id: &'a str,
    pub chat_template_id: Option<&'a str>,
    pub add_generation_prompt: Option<bool>,
    pub continue_final_message: Option<bool>,
    /// Exposed to the template as the `enable_thinking` variable (Qwen3 etc. use
    /// it to gate reasoning). `None` defaults to `true` (the template's own
    /// default); `Some(false)` makes a thinking model emit a closed empty
    /// `<think></think>` in the PROMPT so its output is clean.
    pub enable_thinking: Option<bool>,
    /// Special-token strings exposed to the template as `bos_token` / `eos_token`. Some
    /// templates (Gemma's `{{ bos_token }}`) emit the BOS via the template rather than at
    /// encode time; without these the BOS is silently dropped and a BOS-sensitive model
    /// (Gemma) produces garbage. `None` renders an empty string for that variable.
    pub bos_token: Option<String>,
    pub eos_token: Option<String>,
}

pub fn load_model_chat_template_from_str(content: &str) -> std::io::Result<Option<String>> {
    let value: serde_json::Value = serde_json::from_str(content)?;
    let Some(ct) = value.get("chat_template") else {
        return Ok(None);
    };
    // `chat_template` is either a plain Jinja string, or the older list-of-`{name, template}`
    // form (Mistral / Mistral-Nemo and some others ship multiple named templates). For the
    // list form pick the entry named "default" (the plain-chat template), else the first.
    let template = match ct {
        serde_json::Value::String(s) => Some(s.clone()),
        serde_json::Value::Array(entries) => entries
            .iter()
            .find(|e| e.get("name").and_then(|n| n.as_str()) == Some("default"))
            .or_else(|| entries.first())
            .and_then(|e| e.get("template").and_then(|t| t.as_str()))
            .map(ToString::to_string),
        _ => None,
    };
    Ok(template)
}

pub fn load_model_chat_template_from_file(
    file: impl AsRef<Path>,
) -> std::io::Result<Option<String>> {
    let content = read_to_string(file)?;
    load_model_chat_template_from_str(&content)
}

